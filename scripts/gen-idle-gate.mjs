#!/usr/bin/env node
/**
 * Generates app/styles/idle-gate.css: pauses every looping (infinite) theme
 * animation until <html> gets the `sn-idle` class (added once the page has
 * loaded and the main thread is idle — see app/layout.tsx). The loops are
 * decorative, so starting them a moment later is invisible, but running them
 * from the first frame competes with first paint on phones.
 * One-shot entrance animations are left untouched.
 *
 *   node scripts/gen-idle-gate.mjs   (re-run after adding looping animations)
 */
import fs from 'node:fs';
import path from 'node:path';

const ROOT = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..');
const files = [];
const walk = (d) => {
  for (const f of fs.readdirSync(d, { withFileTypes: true })) {
    const p = path.join(d, f.name);
    if (f.isDirectory()) walk(p);
    else if (f.name.endsWith('.css') && f.name !== 'idle-gate.css') files.push(p);
  }
};
['app/styles', 'components'].forEach((d) => walk(path.join(ROOT, d)));

const selectors = new Set();
for (const f of files) {
  const css = fs.readFileSync(f, 'utf8').replace(/\/\*[\s\S]*?\*\//g, '');
  // walk rules, skipping @keyframes bodies; @media/@supports wrappers are flattened
  const re = /([^{}@][^{}]*)\{([^{}]*)\}/g;
  const stripped = css.replace(/@keyframes[^{]*\{(?:[^{}]*\{[^{}]*\})*[^{}]*\}/g, '');
  for (const m of stripped.matchAll(re)) {
    const sel = m[1].trim(), body = m[2];
    if (!/animation(?:-iteration-count)?\s*:[^;]*\binfinite\b/.test(body)) continue;
    sel.split(/,(?![^(]*\))/).map((s) => s.trim()).filter(Boolean).forEach((s) => selectors.add(s));
  }
}
const list = [...selectors].sort();
const out = `/* Generated by scripts/gen-idle-gate.mjs — do not edit by hand. */
${list.map((s) => `html:not(.sn-idle) ${s.replace(/^(html|:root)\b\s*/, '')}`).join(',\n')} {
  animation-play-state: paused !important;
}
`;
fs.writeFileSync(path.join(ROOT, 'app/styles/idle-gate.css'), out);
console.log(`${list.length} looping selectors gated from ${files.length} stylesheets`);
